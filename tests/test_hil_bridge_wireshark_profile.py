class ProfileFilesTests(unittest.TestCase):
    def setUp(self) -> None:
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name) / "wireshark"

    def _profile(self, name: str = "YggdraSIM-HIL") -> Path:
        return self.root / "profiles" / name

    def test_creates_the_profile_with_both_managed_files(self) -> None:
        self.assertEqual(
            ensure_hil_wireshark_profile("YggdraSIM-HIL", config_dir=self.root, global_colorfilters=GLOBAL_RULES),
            "YggdraSIM-HIL",
        )
        buttons = (self._profile() / "dfilter_buttons").read_text().splitlines()
        self.assertEqual(buttons[0], MANAGED_MARKER)
        self.assertEqual(len(buttons), 1 + len(FILTER_BUTTONS))
        self.assertTrue(all(line.startswith('"TRUE","') and line.count('"') == 8 for line in buttons[1:]))
        colors = (self._profile() / "colorfilters").read_text().splitlines()
        self.assertEqual(colors[0], MANAGED_MARKER)
        self.assertEqual([line.split("@")[1] for line in colors[1 : 1 + len(COLOR_RULES)]], [rule[0] for rule in COLOR_RULES])
        # The global defaults follow ours, comment lines dropped, disabled ones kept.
        self.assertEqual(colors[-2:], GLOBAL_RULES.splitlines()[1:])

    def test_every_gsmtap_row_gets_a_dark_ground(self) -> None:
        """The last rule of ours catches what the others leave, ahead of the light defaults."""
        self.assertEqual(COLOR_RULES[-1][1], "udp.port == 4729")
        for name, _expression, background, foreground in COLOR_RULES:
            with self.subTest(rule=name):
                self.assertNotEqual(background, foreground)
                if name != "YggdraSIM TLS failure":
                    self.assertLess(max(background), 0x5000)
                    self.assertGreater(max(foreground), 0x8000)
        names = [rule[0] for rule in COLOR_RULES]
        # An error keeps its colour on the modem side: first match wins.
        self.assertLess(names.index("YggdraSIM status error"), names.index("YggdraSIM modem side"))
        self.assertLess(names.index("YggdraSIM modem side"), names.index("YggdraSIM toolkit"))

    def test_the_style_sheet_is_passed_as_one_token_and_can_be_emptied(self) -> None:
        ensure_hil_wireshark_profile("YggdraSIM-HIL", config_dir=self.root, global_colorfilters="")
        sheet = self._profile() / STYLESHEET_FILE_NAME
        # Opt-in: preparing the profile alone leaves the desktop's own look.
        self.assertFalse(sheet.exists())
        self.assertEqual(hil_wireshark_stylesheet_args("YggdraSIM-HIL", config_dir=self.root), [])
        self.assertEqual(enable_hil_wireshark_stylesheet("YggdraSIM-HIL", config_dir=self.root), str(sheet))
        self.assertEqual(sheet.read_text(), render_stylesheet())
        # Once there it is kept current.
        sheet.write_text(render_stylesheet().splitlines()[0] + "\nQWidget { color: red; }\n")
        ensure_hil_wireshark_profile("YggdraSIM-HIL", config_dir=self.root, global_colorfilters="")
        self.assertEqual(sheet.read_text(), render_stylesheet())
        self.assertEqual(
            hil_wireshark_stylesheet_args("YggdraSIM-HIL", config_dir=self.root), [f"-stylesheet={sheet}"]
        )
        # An emptied file is the operator's: not rewritten, not passed.
        sheet.write_text("")
        ensure_hil_wireshark_profile("YggdraSIM-HIL", config_dir=self.root, global_colorfilters="")
        self.assertEqual(sheet.read_text(), "")
        self.assertEqual(hil_wireshark_stylesheet_args("YggdraSIM-HIL", config_dir=self.root), [])

    def test_leaves_a_file_without_the_marker_alone(self) -> None:
        profile = self._profile("YggdraSIM-APDU")
        profile.mkdir(parents=True)
        (profile / "preferences").write_text("gui.column.format: \n")
        (profile / "dfilter_buttons").write_text('# This file is automatically generated, DO NOT MODIFY.\n"TRUE","Mine","udp",""\n')
        ensure_hil_wireshark_profile("YggdraSIM-APDU", config_dir=self.root, global_colorfilters="")
        self.assertIn('"Mine"', (profile / "dfilter_buttons").read_text())
        self.assertEqual((profile / "preferences").read_text(), "gui.column.format: \n")
        self.assertTrue((profile / "colorfilters").read_text().startswith(MANAGED_MARKER))

    def test_rewrites_its_own_file_when_the_content_changes(self) -> None:
        profile = self._profile()
        profile.mkdir(parents=True)
        (profile / "colorfilters").write_text(MANAGED_MARKER + "\n@old@udp@[0,0,0][0,0,0]\n")
        ensure_hil_wireshark_profile("YggdraSIM-HIL", config_dir=self.root, global_colorfilters="")
        self.assertEqual((profile / "colorfilters").read_text(), render_colorfilters(""))

    def test_names_that_are_not_a_profile_give_no_profile(self) -> None:
        for name in ("", "Default", "default", "..", "a/b"):
            with self.subTest(name=name):
                self.assertEqual(ensure_hil_wireshark_profile(name, config_dir=self.root), "")
        self.assertFalse((self.root / "profiles").exists())

    def test_an_unwritable_configuration_gives_no_profile_and_no_error(self) -> None:
        self.root.parent.mkdir(parents=True, exist_ok=True)
        self.root.write_text("a file where the directory should be")
        self.assertEqual(ensure_hil_wireshark_profile("YggdraSIM-HIL", config_dir=self.root), "")

    def test_personal_configuration_directory(self) -> None:
        home = Path(self.directory.name)
        self.assertEqual(wireshark_personal_config_dir({"WIRESHARK_CONFIG_DIR": "/opt/ws"}), Path("/opt/ws"))
        self.assertEqual(wireshark_personal_config_dir({"HOME": str(home)}), home / ".config" / "wireshark")
        self.assertEqual(
            wireshark_personal_config_dir({"HOME": str(home), "XDG_CONFIG_HOME": str(home / "xdg")}),
            home / "xdg" / "wireshark",
        )
        (home / ".wireshark").mkdir()
        self.assertEqual(wireshark_personal_config_dir({"HOME": str(home)}), home / ".wireshark")

    def test_rendered_buttons_carry_no_quote_needing_escapes(self) -> None:
        for label, expression, comment in FILTER_BUTTONS:
            for text in (label, expression, comment):
                self.assertNotIn('"', text)
                self.assertNotIn("\\", text)
        self.assertTrue(render_filter_buttons().endswith("\n"))


@unittest.skipIf(shutil.which("tshark") is None, "tshark is not installed")
class FilterExpressionsCompileTests(unittest.TestCase):
    """Every button and colour expression must compile in the installed Wireshark."""

    def _tshark(self, directory: str, *arguments: str) -> subprocess.CompletedProcess[str]:
        """Run tshark on the configuration in *directory*, without the APDU dissector."""
        env = {"HOME": directory, "XDG_CONFIG_HOME": directory, "PATH": os.environ.get("PATH", "/usr/bin:/bin")}
        result = subprocess.run(
            ["tshark", "-n", *arguments],
            capture_output=True,
            text=True,
            env=env,
            timeout=60,
            check=False,
        )
        if result.returncode != 0 and "permission" in result.stderr.lower():
            self.skipTest("tshark cannot read the temporary capture here")
        self.assertEqual(result.returncode, 0, result.stderr)
        return result

    def test_expressions_compile_and_select_the_right_side(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            capture = Path(directory) / "two-sides.pcap"
            writer = GsmtapPcapWriter(path=str(capture))
            payload = build_simtrace_apdu_payload(bytes.fromhex("80F2000C00"), b"\x90\x00")
            writer.write_gsmtap_packet(build_gsmtap_packet(payload, subtype=0, uplink=True))
            writer.write_gsmtap_packet(build_gsmtap_packet(payload, subtype=0, uplink=True, antenna=1))
            writer.close()
            expected = {"SIM side": 1, "Modem side": 1, "Exchanges": 2}
            for label, expression, _comment in FILTER_BUTTONS:
                with self.subTest(button=label):
                    result = self._tshark(directory, "-r", str(capture), "-Y", expression)
                    if label in expected:
                        self.assertEqual(len(result.stdout.splitlines()), expected[label])
            # Wireshark compiles every colour rule at startup, with or without
            # the APDU dissector loaded.
            for name, expression, _background, _foreground in COLOR_RULES:
                with self.subTest(rule=name):
                    self._tshark(directory, "-r", str(capture), "-Y", expression)

    def test_stk_button_selects_the_toolkit_exchanges(self) -> None:
        display_text = "D010" "810301218082028102" "8D050454657374"
        records = (
            # (GSMTAP SIM record, sub-type, antenna, an STK row)
            ("8010000003FFFFFF" "9000", GSMTAP_SIM_APDU, 0, True),  # TERMINAL PROFILE
            ("80F2000C00" "9000", GSMTAP_SIM_APDU, 0, True),  # STATUS, proactive polling
            ("8012000012" + display_text + "9000", GSMTAP_SIM_APDU, 0, True),  # FETCH
            ("8012000012" + display_text + "9000", GSMTAP_SIM_APDU, 1, True),  # FETCH, modem side
            ("801400000C" "810301218082028281830100" "9000", GSMTAP_SIM_APDU, 0, True),  # TERMINAL RESPONSE
            ("80C2000003" "D30100" "9300", GSMTAP_SIM_APDU, 0, True),  # ENVELOPE, toolkit busy
            ("00B0000002" "0102" "9110", GSMTAP_SIM_APDU, 0, True),  # READ BINARY, a proactive command pending
            ("00B0000002" "0102" "62F2", GSMTAP_SIM_APDU, 0, True),  # more data, a proactive command pending
            ("00D6000002" "0102" "63F2", GSMTAP_SIM_APDU, 0, True),  # more data expected, a proactive command pending
            ("00B0000002" "0102" "6282", GSMTAP_SIM_APDU, 0, False),  # READ BINARY, end of file reached
            ("00A40004023F00" "9000", GSMTAP_SIM_APDU, 0, False),  # SELECT
            # Stock gsm_sim reads an ATR record as an APDU: T0 '12' is INS FETCH.
            ("3B12960102", GSMTAP_SIM_ATR, 0, False),
        )
        with tempfile.TemporaryDirectory() as directory:
            capture = Path(directory) / "stk.pcap"
            writer = GsmtapPcapWriter(path=str(capture))
            for record, subtype, antenna, _stk in records:
                packet = build_gsmtap_packet(bytes.fromhex(record), subtype=subtype, uplink=True, antenna=antenna)
                writer.write_gsmtap_packet(packet)
            writer.close()
            result = self._tshark(directory, "-r", str(capture), "-Y", STK_FILTER, "-T", "fields", "-e", "frame.number")
        expected = [str(number) for number, record in enumerate(records, start=1) if record[3]]
        self.assertEqual(result.stdout.split(), expected)

    def test_each_row_takes_the_rule_of_its_kind(self) -> None:
        records = (
            # (GSMTAP SIM record, sub-type, antenna, colouring rule)
            ("00A40004023F00" "9000", GSMTAP_SIM_APDU, 0, "YggdraSIM session"),
            ("00B0000002" "0102" "9000", GSMTAP_SIM_APDU, 0, "YggdraSIM read"),
            ("00D6000002" "0102" "9000", GSMTAP_SIM_APDU, 0, "YggdraSIM write"),
            ("0020000108" "31323334FFFFFFFF" "9000", GSMTAP_SIM_APDU, 0, "YggdraSIM authentication"),
            ("0020000108" "31323334FFFFFFFF" "63C2", GSMTAP_SIM_APDU, 0, "YggdraSIM status warning"),
            ("00A40004026F07" "6A82", GSMTAP_SIM_APDU, 0, "YggdraSIM status error"),
            ("00A40004026F07" "6A82", GSMTAP_SIM_APDU, 1, "YggdraSIM status error"),
            ("00A40004022FE2" "6113", GSMTAP_SIM_APDU, 0, "YggdraSIM session"),
            ("A0A40000023F00" "9F17", GSMTAP_SIM_APDU, 0, "YggdraSIM session"),
            ("80F2000C00" "9000", GSMTAP_SIM_APDU, 0, "YggdraSIM toolkit"),
            ("00B0000002" "0102" "9000", GSMTAP_SIM_APDU, 1, "YggdraSIM modem side"),
            ("80AB000100" "9000", GSMTAP_SIM_APDU, 0, "YggdraSIM GSMTAP"),
            ("3B12960102", GSMTAP_SIM_ATR, 0, "YggdraSIM ATR"),
        )
        with tempfile.TemporaryDirectory() as directory:
            capture = Path(directory) / "kinds.pcap"
            writer = GsmtapPcapWriter(path=str(capture))
            for record, subtype, antenna, _rule in records:
                packet = build_gsmtap_packet(bytes.fromhex(record), subtype=subtype, uplink=True, antenna=antenna)
                writer.write_gsmtap_packet(packet)
            writer.close()
            ensure_hil_wireshark_profile(
                "YggdraSIM-HIL", config_dir=Path(directory) / "wireshark", global_colorfilters=GLOBAL_RULES
            )
            result = self._tshark(
                directory, "-C", "YggdraSIM-HIL", "--color", "-r", str(capture),
                "-T", "fields", "-e", "frame.coloring_rule.name",
            )
        self.assertEqual(result.stdout.splitlines(), [record[3] for record in records])

    def test_the_buttons_load_as_a_wireshark_table(self) -> None:
        # Wireshark reports a record it cannot parse as an error loading its
        # "Display expressions" table; the STK expression carries commas and braces.
        with tempfile.TemporaryDirectory() as directory:
            capture = Path(directory) / "one.pcap"
            writer = GsmtapPcapWriter(path=str(capture))
            payload = build_simtrace_apdu_payload(bytes.fromhex("80F2000C00"), b"\x90\x00")
            writer.write_gsmtap_packet(build_gsmtap_packet(payload, subtype=GSMTAP_SIM_APDU, uplink=True))
            writer.close()
            profile = ensure_hil_wireshark_profile(
                "YggdraSIM-HIL", config_dir=Path(directory) / "wireshark", global_colorfilters=""
            )
            self.assertEqual(profile, "YggdraSIM-HIL")
            result = self._tshark(directory, "-C", profile, "-r", str(capture))
        self.assertNotIn("Error loading table", result.stderr)


